// Stat help and glossary, keyed by stat id (site/src/lib/stats.ts).
// Each entry: short column label, full name, what it is, how to read it, and its scouting use.
// Text that differs for hitters and pitchers is given per role.
// The league average shown in the help popover comes from league.json, so it stays current.

export type PerRole = string | { batting: string; pitching: string };

export interface GlossaryEntry {
  label: PerRole;
  name: PerRole;
  what: PerRole;
  read: PerRole;
  use: PerRole;
  /** Show the league average as a reference point (rates only; totals depend on playing time). */
  league?: boolean;
}

export function pick(text: PerRole, role: 'batting' | 'pitching'): string {
  return typeof text === 'string' ? text : text[role];
}

